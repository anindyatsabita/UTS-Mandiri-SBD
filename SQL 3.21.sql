DROP SCHEMA IF EXISTS voting_house CASCADE;
CREATE SCHEMA voting_house;
SET search_path TO voting_house, public;

CREATE TABLE state (
    state_name VARCHAR(100) PRIMARY KEY,
    region VARCHAR(20) NOT NULL
        CHECK (region IN ('Northeast', 'Midwest', 'Southeast', 'Southwest', 'West'))
);

CREATE TABLE congress_person (
    person_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    district_no INTEGER NOT NULL CHECK (district_no > 0),
    start_date DATE NOT NULL,
    party VARCHAR(20) NOT NULL
        CHECK (party IN ('Republican', 'Democrat', 'Independent', 'Other')),
    state_name VARCHAR(100) NOT NULL REFERENCES state(state_name),
    UNIQUE (state_name, district_no)
);

CREATE TABLE bill (
    bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_name VARCHAR(300) NOT NULL,
    date_of_vote DATE NOT NULL,
    passed_or_failed VARCHAR(3) NOT NULL
        CHECK (passed_or_failed IN ('Yes', 'No'))
);

CREATE TABLE bill_sponsor (
    bill_id BIGINT NOT NULL REFERENCES bill(bill_id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES congress_person(person_id),
    PRIMARY KEY (bill_id, person_id)
);

CREATE TABLE bill_vote (
    bill_id BIGINT NOT NULL REFERENCES bill(bill_id) ON DELETE CASCADE,
    person_id BIGINT NOT NULL REFERENCES congress_person(person_id),
    vote_status VARCHAR(10) NOT NULL
        CHECK (vote_status IN ('Yes', 'No', 'Abstain', 'Absent')),
    PRIMARY KEY (bill_id, person_id)
);

