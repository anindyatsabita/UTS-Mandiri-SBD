SELECT b.bill_name, cp.full_name, v.vote_status
FROM bill_vote AS v
JOIN bill AS b ON b.bill_id = v.bill_id
JOIN congress_person AS cp ON cp.person_id = v.person_id
ORDER BY cp.person_id;

