SELECT p.paper_id, p.title, r.first_name || ' ' || r.last_name AS reviewer,
       ra.technical_merit, ra.readability, ra.originality, ra.relevance,
       ra.recommendation
FROM review_assignment AS ra
JOIN paper AS p ON p.paper_id = ra.paper_id
JOIN reviewer AS r ON r.reviewer_email = ra.reviewer_email
ORDER BY r.reviewer_email;

SELECT p.paper_id, p.title, COUNT(ra.reviewer_email) AS reviewer_count
FROM paper AS p
LEFT JOIN review_assignment AS ra ON ra.paper_id = p.paper_id
GROUP BY p.paper_id, p.title
ORDER BY p.paper_id;
