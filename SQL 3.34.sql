DROP SCHEMA IF EXISTS conference_review CASCADE;
CREATE SCHEMA conference_review;
SET search_path TO conference_review, public;

CREATE TABLE author (
    author_email VARCHAR(254) PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL
);

CREATE TABLE reviewer (
    reviewer_email VARCHAR(254) PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    phone_number VARCHAR(40) NOT NULL,
    affiliation VARCHAR(200) NOT NULL
);

CREATE TABLE reviewer_topic (
    reviewer_email VARCHAR(254) NOT NULL
        REFERENCES reviewer(reviewer_email) ON DELETE CASCADE,
    topic_name VARCHAR(120) NOT NULL,
    PRIMARY KEY (reviewer_email, topic_name)
);

CREATE TABLE paper (
    paper_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(300) NOT NULL,
    abstract TEXT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    contact_author_email VARCHAR(254) NOT NULL
);

CREATE TABLE paper_author (
    paper_id BIGINT NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    author_email VARCHAR(254) NOT NULL REFERENCES author(author_email),
    PRIMARY KEY (paper_id, author_email)
);

ALTER TABLE paper
    ADD CONSTRAINT fk_paper_contact_author_membership
    FOREIGN KEY (paper_id, contact_author_email)
    REFERENCES paper_author (paper_id, author_email)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE review_assignment (
    paper_id BIGINT NOT NULL REFERENCES paper(paper_id) ON DELETE CASCADE,
    reviewer_email VARCHAR(254) NOT NULL REFERENCES reviewer(reviewer_email),
    technical_merit SMALLINT NOT NULL CHECK (technical_merit BETWEEN 1 AND 10),
    readability SMALLINT NOT NULL CHECK (readability BETWEEN 1 AND 10),
    originality SMALLINT NOT NULL CHECK (originality BETWEEN 1 AND 10),
    relevance SMALLINT NOT NULL CHECK (relevance BETWEEN 1 AND 10),
    recommendation VARCHAR(10) NOT NULL CHECK (recommendation IN ('Accept', 'Reject')),
    committee_comments TEXT NOT NULL,
    author_feedback TEXT NOT NULL,
    PRIMARY KEY (paper_id, reviewer_email)
);

CREATE OR REPLACE FUNCTION assert_review_count(p_paper_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql AS $$
DECLARE
    reviewer_count INTEGER;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM paper WHERE paper_id = p_paper_id) THEN
        RETURN;
    END IF;

    SELECT COUNT(*) INTO reviewer_count
    FROM review_assignment
    WHERE paper_id = p_paper_id;

    IF reviewer_count < 2 OR reviewer_count > 4 THEN
        RAISE EXCEPTION
            'Paper % must have 2-4 reviewers; final count is %',
            p_paper_id, reviewer_count;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION check_review_assignment_count()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM assert_review_count(OLD.paper_id);
    ELSIF TG_OP = 'UPDATE' THEN
        PERFORM assert_review_count(OLD.paper_id);
        IF NEW.paper_id IS DISTINCT FROM OLD.paper_id THEN
            PERFORM assert_review_count(NEW.paper_id);
        END IF;
    ELSE
        PERFORM assert_review_count(NEW.paper_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION check_paper_reviewer_count()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM assert_review_count(OLD.paper_id);
    ELSE
        PERFORM assert_review_count(NEW.paper_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_assignment_reviewer_count
AFTER INSERT OR UPDATE OR DELETE ON review_assignment
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_review_assignment_count();

CREATE CONSTRAINT TRIGGER trg_paper_reviewer_count
AFTER INSERT OR UPDATE OR DELETE ON paper
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_paper_reviewer_count();

